// Faint dotted world map, drawn from a hand-tuned 69×26 land bitmap.
// Purely decorative — aria-hidden, used at low opacity.

const MAP = [
  '.........................####.............######.####.#######........',
  '.####...##############.####.............#############################.',
  '..###..###################.###......###..############################',
  '....#####################..#....#...#################################.',
  '.....###################.##....##.####.####################.#####....',
  '......#################..........########...#############....##......',
  '.......##############..........###.##########..#######......##.......',
  '......##############............######.#####..###..###..##..#........',
  '.......#############.............########.####.#####.......#........',
  '........##########..............##########....####....####...........',
  '.........#########..............#########......###....####...........',
  '..........#######...............##########.....##......###...........',
  '...........######.#####........##########............#######........',
  '..........#########...........##########............#######.........',
  '..........#########...........##########...............#####........',
  '..........#########............########................##...........',
  '...........########............######...............................',
  '...........########............#####..........#########.............',
  '...........#######.............####..........###########............',
  '...........#######.............####.........############............',
  '............######..............###..........###########............',
  '............######...............##...........#########.............',
  '.............#####.............................########..............',
  '.............####................................####................',
  '..............##.....................................#..............',
  '..............##.....................................#..............',
]

export function DottedMap({ className = '' }: { className?: string }) {
  const dots: { x: number; y: number }[] = []
  const step = 14
  MAP.forEach((row, y) => {
    row
      .padEnd(69, '.')
      .split('')
      .forEach((ch, x) => {
        if (ch === '#') dots.push({ x: x * step, y: y * step })
      })
  })
  return (
    <svg
      aria-hidden
      className={className}
      width={69 * step}
      height={MAP.length * step}
      viewBox={`0 0 ${69 * step} ${MAP.length * step}`}
      fill="currentColor"
    >
      {dots.map((d, i) => (
        <circle key={i} cx={d.x + 4} cy={d.y + 4} r={2.1} />
      ))}
    </svg>
  )
}
